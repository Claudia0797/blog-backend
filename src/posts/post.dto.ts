import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { CategoryDto } from 'src/categories/category.dto';

export class PostDto {
  @ApiPropertyOptional({
    description: 'Post id (UUID). Generated by the API.',
    example: '9a9f2c22-3c5b-4a15-9d2d-0f1c2a3b4c5d',
    format: 'uuid',
  })
  readonly postId?: string;

  @ApiProperty({
    description: 'Post title',
    example: 'Mi primera entrada en el blog',
    maxLength: 120,
  })
  readonly title: string;

  @ApiProperty({
    description: 'Post content/description',
    example: 'En esta entrada explico cómo he montado la práctica 1...',
  })
  readonly description: string;

  @ApiProperty({
    description: 'Number of likes',
    example: 0,
    minimum: 0,
  })
  readonly num_likes: number;

  @ApiProperty({
    description: 'Number of dislikes',
    example: 0,
    minimum: 0,
  })
  readonly num_dislikes: number;

  @ApiProperty({
    description: 'Publication date (ISO 8601)',
    example: '2026-02-17T20:21:56.000Z',
    format: 'date-time',
  })
  readonly publication_date: Date;

  @ApiProperty({
    description: 'Author user id (UUID)',
    example: 'b8f5a2c1-1234-4cde-9a12-ff00aa11bb22',
    format: 'uuid',
  })
  readonly userId: string;

  @ApiPropertyOptional({
    description: 'Author alias (optional, derived)',
    example: 'adal',
  })
  readonly userAlias?: string;

  @ApiProperty({
    description: 'Categories assigned to the post',
    type: CategoryDto,
    isArray: true,
    example: [{ id: '5e1a7d10-8b4c-4f4d-9c11-1a2b3c4d5e6f', name: 'Angular' }],
  })
  readonly categories: CategoryDto[];

  constructor(
    postId: string,
    title: string,
    description: string,
    num_likes: number,
    num_dislikes: number,
    publication_date: Date,
    userId: string,
    userAlias: string,
    categories: CategoryDto[],
  ) {
    this.postId = postId;
    this.title = title;
    this.description = description;
    this.num_likes = num_likes;
    this.num_dislikes = num_dislikes;
    this.publication_date = publication_date;
    this.userId = userId;
    this.userAlias = userAlias;
    this.categories = categories;
  }
}
