import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class UserDto {
  @ApiPropertyOptional({
    description: 'User id (UUID). Generated by the API.',
    example: 'b8f5a2c1-1234-4cde-9a12-ff00aa11bb22',
    format: 'uuid',
  })
  readonly id?: string;

  @ApiProperty({
    description: 'User first name',
    example: 'Ada',
    maxLength: 80,
  })
  readonly name: string;

  @ApiProperty({
    description: 'User first surname',
    example: 'Lovelace',
    maxLength: 80,
  })
  readonly surname_1: string;

  @ApiPropertyOptional({
    description: 'User second surname (optional)',
    example: 'Byron',
    maxLength: 80,
  })
  readonly surname_2?: string;

  @ApiProperty({
    description: 'Public alias (must be unique)',
    example: 'adal',
    maxLength: 40,
  })
  readonly alias: string;

  @ApiProperty({
    description: 'Email (must be unique)',
    example: 'ada@uoc.edu',
    format: 'email',
    maxLength: 120,
  })
  readonly email: string;

  @ApiProperty({
    description:
      'Password. Used for register/login/update. It should never be returned in responses.',
    example: '123456',
    minLength: 6,
  })
  readonly password: string;

  @ApiPropertyOptional({
    description: 'Birth date (YYYY-MM-DD)',
    example: '1990-05-20',
    format: 'date',
  })
  readonly birth_date?: Date;

  @ApiPropertyOptional({
    description: 'Post ids created by the user',
    example: ['9a9f2c22-3c5b-4a15-9d2d-0f1c2a3b4c5d'],
    isArray: true,
    type: String,
  })
  readonly posts?: string[];

  @ApiPropertyOptional({
    description: 'Category ids created by the user',
    example: ['5e1a7d10-8b4c-4f4d-9c11-1a2b3c4d5e6f'],
    isArray: true,
    type: String,
  })
  readonly categories?: string[];

  constructor(
    id: string,
    name: string,
    surname_1: string,
    surname_2: string,
    alias: string,
    email: string,
    password: string,
    birth_date: Date,
  ) {
    this.id = id;
    this.name = name;
    this.surname_1 = surname_1;
    this.surname_2 = surname_2;
    this.alias = alias;
    this.email = email;
    this.password = password;
    this.birth_date = birth_date;
  }
}
