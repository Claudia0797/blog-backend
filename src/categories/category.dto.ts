import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class CategoryDto {
  @ApiPropertyOptional({
    description: 'Category id (UUID). Generated by the API.',
    example: '5e1a7d10-8b4c-4f4d-9c11-1a2b3c4d5e6f',
    format: 'uuid',
  })
  readonly categoryId?: string;

  @ApiProperty({
    description: 'Category title (must be unique)',
    example: 'Angular',
    maxLength: 60,
  })
  readonly title: string;

  @ApiProperty({
    description: 'Category description',
    example: 'Recursos y prácticas relacionadas con Angular.',
  })
  readonly description: string;

  @ApiProperty({
    description: 'CSS color (must be unique). Example: hex color.',
    example: '#ffcc00',
    pattern: '^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$',
  })
  readonly css_color: string;

  @ApiProperty({
    description: 'Owner user id (UUID)',
    example: 'b8f5a2c1-1234-4cde-9a12-ff00aa11bb22',
    format: 'uuid',
  })
  readonly userId: string;

  constructor(
    categoryId: string,
    title: string,
    description: string,
    css_color: string,
    userId: string,
  ) {
    this.categoryId = categoryId;
    this.title = title;
    this.description = description;
    this.css_color = css_color;
    this.userId = userId;
  }
}
